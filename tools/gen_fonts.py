#!/usr/bin/env python3
"""Generate os/components/cpos_core/font_data.c.

Fonts are rasterized once from DejaVu Sans (free Bitstream Vera/DejaVu license) as
1-bit hinted bitmaps; the 6x8 base font is the classic 5x7 GLCD table from
Adafruit-GFX (BSD). The generated file is checked in; this script is only needed
to change the font set:  python3 tools/gen_fonts.py <glcdfont.c> <DejaVuSans.ttf>
"""
import re, sys, freetype, pathlib

glcd_src, ttf = sys.argv[1], sys.argv[2]
out = pathlib.Path(__file__).resolve().parents[1] / "os/components/cpos_core/font_data.c"

LATIN1 = list(range(32, 127)) + list(range(160, 256))
EXTRA = [0x3C9, 0x266A, 0x266D, 0x266F, 0x25B2, 0x25BC, 0x2192, 0x2190, 0x2713, 0x2022, 0x2026]
SMALL = LATIN1 + EXTRA
BIG40 = [ord(c) for c in " 0123456789:.-+%#/ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"] + [0xB0, 0x266D, 0x266F]
BIG56 = [ord(c) for c in " 0123456789:.-+%#/ABCDEFGabcdefgNSEW"] + [0xB0, 0x266D, 0x266F]

# name, ft pixel size, codepoints
FONTS = [
    ("font2", 14, SMALL), ("font4", 22, SMALL),
    ("dejavu18", 18, SMALL), ("dejavu24", 24, SMALL),
    ("dejavu40", 40, BIG40), ("dejavu56", 56, BIG56), ("dejavu72", 72, BIG56),
    ("jp12", 10, SMALL), ("jp16", 14, SMALL),
]

face = freetype.Face(ttf)
lines = ['/* generated by tools/gen_fonts.py - do not edit */',
         '#include "font.h"', '']

# ---- GLCD 5x7 base font -----------------------------------------------------
txt = pathlib.Path(glcd_src).read_text()
body = txt[txt.index("{", txt.index("font[]")) + 1: txt.index("};")]
data = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", body)]
assert len(data) == 1280, len(data)
lines.append("const uint8_t cpos_glcd_font[1280] = {")
for i in range(0, 1280, 16):
    lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
lines.append("};")
lines.append("")

for name, px, cps in FONTS:
    face.set_pixel_sizes(0, px)
    glyphs, blob = [], bytearray()
    asc = face.size.ascender >> 6
    desc = -(face.size.descender >> 6)
    height = asc + desc
    for cp in cps:
        gi = face.get_char_index(cp)
        if gi == 0 and cp != 32:
            continue
        face.load_glyph(gi, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO)
        g = face.glyph
        bm = g.bitmap
        w, h, pitch = bm.width, bm.rows, bm.pitch
        adv = g.advance.x >> 6
        off = len(blob)
        # pack rows MSB first, each row byte aligned
        rb = (w + 7) // 8
        for r in range(h):
            row = bytes(bm.buffer[r * pitch: r * pitch + rb])
            blob += row
        glyphs.append((cp, off, w, h, g.bitmap_left, g.bitmap_top, adv))
    lines.append(f"static const uint8_t {name}_bm[{len(blob)}] = {{")
    for i in range(0, len(blob), 24):
        lines.append("    " + ",".join("0x%02X" % b for b in blob[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const cpos_glyph_t {name}_gl[{len(glyphs)}] = {{")
    for cp, off, w, h, xl, yt, adv in glyphs:
        lines.append(f"    {{0x{cp:04X},{off},{w},{h},{xl},{yt},{adv}}},")
    lines.append("};")
    lines.append(f"const cpos_font_t cpos_{name} = {{{name}_bm, {name}_gl, {len(glyphs)}, {height}, {asc}}};")
    lines.append("")
    print(name, px, len(glyphs), "glyphs", len(blob), "bytes", "h", height)

out.write_text("\n".join(lines) + "\n")
