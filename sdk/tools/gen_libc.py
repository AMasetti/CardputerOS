#!/usr/bin/env python3
"""Generate the libc part of the ABI from sdk/libc_exports.def.

Outputs (all checked in, regenerate after editing the .def):
  sdk/include/cpos/libc_table.h        struct cpos_libc_t
  sdk/shim/src/libc_stubs.c            app-side wrappers that call through the table
  os/components/cpos_core/libc_fill.inc   OS-side initializers
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "sdk/libc_exports.def").read_text().splitlines()

entries = []
for line in src:
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    os_sym = None
    m = re.search(r"\s@os=(\w+)\s*$", line)
    if m:
        os_sym = m.group(1)
        line = line[: m.start()].strip()
    m = re.match(r"^(.*?)(\w+)\((.*)\)$", line)
    if not m:
        sys.exit("cannot parse: " + line)
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    plist = []
    if args and args != "void":
        # split on commas not inside parentheses
        depth, cur = 0, ""
        for ch in args:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            if ch == "," and depth == 0:
                plist.append(cur.strip()); cur = ""
            else:
                cur += ch
        plist.append(cur.strip())
    entries.append((ret, name, plist, os_sym))

def argname(p):
    # function-pointer parameter: "int (*cmp)(const void *, const void *)"
    m = re.search(r"\(\*(\w+)\)", p)
    if m:
        return m.group(1)
    return re.search(r"(\w+)$", p).group(1)

hdr = ["/* generated by sdk/tools/gen_libc.py from sdk/libc_exports.def - do not edit */",
       "#ifndef CPOS_LIBC_TABLE_H", "#define CPOS_LIBC_TABLE_H",
       "#include <stdarg.h>", "#include <stddef.h>", "#include <stdio.h>", "#include <stdlib.h>",
       "#include <string.h>", "#include <ctype.h>", "#include <unistd.h>", "#include <math.h>", "#include <dirent.h>", "#include <sys/stat.h>", "#include <sys/types.h>",
       "typedef struct {"]
stub = ["/* generated by sdk/tools/gen_libc.py - do not edit */",
        "#include <cpos/abi.h>", "extern const cpos_api_t *cpos_api;",
        "/* newlib defines these as macros in C */"] + [f"#undef {n}" for n in
        "isalpha isdigit isalnum isspace isupper islower isprint isxdigit ispunct toupper tolower feof ferror".split()] + [""]
fill = ["/* generated by sdk/tools/gen_libc.py - do not edit */"]

for ret, name, plist, os_sym in entries:
    fname = name
    if name == "cpos_vprintf":
        field = "vprintf"
    else:
        field = name
    # struct field type
    if any("(*" in p for p in plist):
        params = ", ".join(plist)
    else:
        params = ", ".join(plist) if plist else "void"
    hdr.append(f"    {ret} (*{field})({params});")
    call_args = ", ".join(argname(p) for p in plist)
    if name in ("cpos_vprintf", "vsnprintf"):
        continue  # written by hand in sdk/shim/src/crt.cpp
    sig = ", ".join(plist) if plist else "void"
    body = f"cpos_api->libc.{field}({call_args})"
    stub.append(f"{ret} {name}({sig}) {{ " + ("" if ret == "void" else "return ") + body + "; }")
    if name == "abort":
        stub[-1] = "void abort(void) { cpos_api->libc.abort(); for (;;) {} }"

hdr += ["} cpos_libc_t;", "#endif", ""]
for ret, name, plist, os_sym in entries:
    field = "vprintf" if name == "cpos_vprintf" else name
    fill.append(f"    .{field} = {os_sym or name},")

(root / "sdk/include/cpos/libc_table.h").write_text("\n".join(hdr))
(root / "sdk/shim/src/libc_stubs.c").write_text("\n".join(stub) + "\n")
(root / "os/components/cpos_core/libc_fill.inc").write_text("\n".join(fill) + "\n")
print(f"{len(entries)} libc entries")
